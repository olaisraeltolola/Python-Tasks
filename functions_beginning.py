def add_two_numbers(number_one, number_two):
	return number_one + number_two

def subtract_two_numbers(number_one, number_two):
	return number_one - number_two

def multiply_two_numbers(number_one, number_two):
	return number_one * number_two

def divide_two_numbers(number_one, number_two):
	return number_one / number_two

def exponential_of_number(number, power):
	return number ** power

print(add_two_numbers(5,7))
print(subtract_two_numbers(10,7))
print(multiply_two_numbers(5,7))
print(divide_two_numbers(14,8))
print(exponential_of_number(5,3))

