principal = 1000
rate = 0.07
amount_after_ten_years = principal * (1 + rate)**10
amount_after_twenty_years = principal * (1 + rate)**20
amount_after_thirty_years = principal * (1 + rate)**30

print("The amount of money you'll have after 10 years is $", amount_after_ten_years, sep="")
print("The amount of money you'll have after 20 years is $", amount_after_twenty_years, sep="")
print("The amount of money you'll have after 30 years is $", amount_after_thirty_years, sep="")